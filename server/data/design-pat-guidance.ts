export function getDesignPatGuidance(language: "en" | "af" = "en"): string {
  return language === "af" ? DESIGN_PAT_GUIDANCE_AF : DESIGN_PAT_GUIDANCE_EN;
}

export function isPatGuidanceMemo(memoText: string | null | undefined): boolean {
  return typeof memoText === "string" && memoText.startsWith(PAT_GUIDANCE_MARKER);
}

export function stripPatGuidanceMarker(memoText: string): string {
  return memoText.startsWith(PAT_GUIDANCE_MARKER)
    ? memoText.slice(PAT_GUIDANCE_MARKER.length).trim()
    : memoText;
}
